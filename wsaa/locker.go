package wsaa

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"sync"
	"time"
)

// DefaultLockTTL is how long a distributed login lock is held at most. It must
// exceed the LoginCms duration (SOAP timeout plus retries) so the lock does not
// expire mid-login; if the holder dies, others take over after this TTL.
const DefaultLockTTL = 60 * time.Second

// defaultLockPoll is how often a waiting instance re-checks the lock and the
// token store while another instance is logging in.
const defaultLockPoll = 250 * time.Millisecond

// Locker is an optional distributed lock that CachedClient uses to coalesce
// LoginCms calls ACROSS processes (e.g. several replicas sharing a Redis
// TokenStore). Without it, coalescing is per process only: two replicas with a
// cache miss would both call LoginCms and WSAA rejects the second one with
// coe.alreadyAuthenticated.
//
// The lock key is the token key plus ":lock" (e.g.
// "wsaa:prod:20123456789:wsfe:lock"). owner is a random value generated by
// CachedClient for each acquisition.
//
// A Redis implementation is two commands:
//
//	TryLock: SET key owner NX PX ttl            → acquired if the reply is OK
//	Unlock:  if GET key == owner then DEL key   (atomically, in a Lua script)
type Locker interface {
	// TryLock tries to take the lock for key without blocking. It returns
	// false (and a nil error) when another owner holds it. The lock must
	// expire on its own after ttl.
	TryLock(ctx context.Context, key, owner string, ttl time.Duration) (bool, error)

	// Unlock releases the lock only if it is still held by owner.
	Unlock(ctx context.Context, key, owner string) error
}

// MemoryLocker is an in-process Locker. It only coordinates CachedClients
// within one process, so it is meant for tests and single-instance
// deployments; for several replicas use a shared lock (Redis, Postgres
// advisory locks, ...).
type MemoryLocker struct {
	mu    sync.Mutex
	locks map[string]memoryLock
}

type memoryLock struct {
	owner   string
	expires time.Time
}

// NewMemoryLocker creates an in-process Locker.
func NewMemoryLocker() *MemoryLocker {
	return &MemoryLocker{locks: make(map[string]memoryLock)}
}

func (m *MemoryLocker) TryLock(_ context.Context, key, owner string, ttl time.Duration) (bool, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	if l, ok := m.locks[key]; ok && l.owner != owner && time.Now().Before(l.expires) {
		return false, nil
	}
	m.locks[key] = memoryLock{owner: owner, expires: time.Now().Add(ttl)}
	return true, nil
}

func (m *MemoryLocker) Unlock(_ context.Context, key, owner string) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	if l, ok := m.locks[key]; ok && l.owner == owner {
		delete(m.locks, key)
	}
	return nil
}

// newLockOwner returns a random owner id for one lock acquisition.
func newLockOwner() (string, error) {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}
